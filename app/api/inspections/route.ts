/**
 * Generate inspection number once on creation.
 * Format: FI_MPSS_#### with an incrementing 4-digit counter.
 * Once assigned, it is never changed on autosaves or updates.
 */
async function generateInspectionNumber(): Promise<string> {
  let existingNumbers: string[] = [];

  try {
    const existing = await prisma.inspection.findMany({
      select: { inspectionNumber: true },
    });
    existingNumbers = existing.map((item: { inspectionNumber: string }) => item.inspectionNumber);
  } catch (dbErr: any) {
    console.warn('[GENERATE-NUMBER] Prisma query error, trying Supabase REST fallback:', dbErr?.message);
    const supabaseUrl = process.env.NEXT_PUBLIC_SUPABASE_URL || process.env.SUPABASE_URL;
    const anonKey = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY || process.env.SUPABASE_ANON_KEY;
    if (supabaseUrl && anonKey) {
      try {
        const res = await fetch(`${supabaseUrl}/rest/v1/Inspection?select=inspectionNumber`, {
          headers: { apikey: anonKey, Authorization: `Bearer ${anonKey}` },
          cache: 'no-store',
        });
        if (res.ok) {
          const rows = await res.json();
          existingNumbers = rows.map((r: any) => r.inspectionNumber);
        }
      } catch (fetchErr) {
        console.warn('[GENERATE-NUMBER] Supabase REST fetch error:', fetchErr);
      }
    }
  }

  let maxNum = 0;
  for (const numStr of existingNumbers) {
    const match = numStr?.match(/^FI_MPSS_(\d+)$/i);
    if (match) {
      const parsed = parseInt(match[1], 10);
      if (!isNaN(parsed) && parsed > maxNum) {
        maxNum = parsed;
      }
    }
  }

  // If no FI_MPSS_ records found, base initial counter on total existing inspections
  if (maxNum === 0 && existingNumbers.length > 0) {
    maxNum = existingNumbers.length;
  }

  let nextNum = maxNum + 1;
  return `FI_MPSS_${nextNum.toString().padStart(4, '0')}`;
}

async function safeInsertNewRecord(recordData: any, isAutoGenerated: boolean): Promise<any> {
  let attempts = 0;
  while (attempts < 5) {
    attempts++;
    try {
      try {
        return await prisma.inspection.create({ data: recordData });
      } catch (prismaErr: any) {
        if (prismaErr.code === 'P2002') throw prismaErr;
        return await sbCreateInspection(recordData);
      }
    } catch (err: any) {
      const isUniqueError = err.code === 'P2002' || err.code === '23505' || err.message?.includes('Unique constraint');
      if (isUniqueError && isAutoGenerated && attempts < 5) {
        await new Promise((r) => setTimeout(r, 60 + Math.random() * 150));
        recordData.inspectionNumber = await generateInspectionNumber();
        continue;
      }
      throw err;
    }
  }
}

export async function GET(req: Request) {
  try {
    const { searchParams } = new URL(req.url);
    const status = searchParams.get('status');

    let inspections: any[] = [];
    try {
      const whereClause: any = {};
      if (status && status !== 'all') {
        whereClause.status = status;
      }

      inspections = await prisma.inspection.findMany({
        where: whereClause,
        orderBy: { updatedAt: 'desc' },
        include: {
          measurements: true,
          defects: true,
          photos: true,
          versions: { orderBy: { versionNumber: 'desc' } },
          auditLogs: { orderBy: { timestamp: 'desc' } },
        },
      });
    } catch {
      inspections = await sbListInspections(status || undefined);
    }

    return NextResponse.json({ inspections });
  } catch (error: any) {
    console.error('Error fetching inspections:', error);
    return NextResponse.json({ error: error.message || 'Failed to fetch inspections' }, { status: 500 });
  }
}

export async function POST(req: Request) {
  try {
    const body = await req.json();
    const {
      id,
      inspectionNumber: providedInspectionNumber,
      poNumber = '',
      poQuantity = 0,
      inspectionQuantity = 0,
      factoryName = '',
      agentName = '',
      season = '',
      buyerBrand = '',
      styleNumber = '',
      productDescription = '',
      inspectionDate = new Date().toISOString().split('T')[0],
      inspectorName = '',
      visualAuditResult = 'PASS',
      packingAuditResult = 'PASS',
      overallResult = 'PASS',
      comments = '',
      itemsToCheck = [],
      shipmentDetails = {},
      cartonDetails = [],
      capDetails = [],
      measurements = [],
      defects = [],
      photos = [],
      status = 'draft',
      currentVersion = 1,
    } = body;

    let inspection: any;

    if (id) {
      // Check if existing record exists
      let existing: any = null;
      try {
        existing = await prisma.inspection.findUnique({ where: { id } });
      } catch {
        existing = await sbFindInspectionById(id);
      }

      if (existing) {
        // Strict Validation: Reject attempts to modify the permanent Report Number
        if (
          providedInspectionNumber &&
          providedInspectionNumber.trim() !== '' &&
          providedInspectionNumber.trim() !== existing.inspectionNumber
        ) {
          return NextResponse.json(
            {
              error: `Report Number is permanent and cannot be modified after creation (Assigned: ${existing.inspectionNumber}).`,
            },
            { status: 400 }
          );
        }

        // Update existing draft. CRITICAL: Never alter or regenerate inspectionNumber on update!
        const updateData = {
          inspectionNumber: existing.inspectionNumber, // Permanently locked to existing record
          poNumber: poNumber ?? '',
          poQuantity: Number(poQuantity) || 0,
          inspectionQuantity: Number(inspectionQuantity) || 0,
          factoryName: factoryName ?? '',
          agentName: agentName ?? '',
          season: season ?? '',
          buyerBrand: buyerBrand ?? '',
          styleNumber: styleNumber ?? '',
          productDescription: productDescription ?? '',
          inspectionDate: inspectionDate || new Date().toISOString().split('T')[0],
          inspectorName: inspectorName ?? '',
          visualAuditResult: visualAuditResult ?? 'PASS',
          packingAuditResult: packingAuditResult ?? 'PASS',
          overallResult: overallResult ?? 'PASS',
          comments: comments ?? '',
          itemsToCheck: typeof itemsToCheck === 'string' ? itemsToCheck : JSON.stringify(itemsToCheck),
          shipmentDetails: typeof shipmentDetails === 'string' ? shipmentDetails : JSON.stringify(shipmentDetails),
          cartonDetails: typeof cartonDetails === 'string' ? cartonDetails : JSON.stringify(cartonDetails),
          capDetails: typeof capDetails === 'string' ? capDetails : JSON.stringify(capDetails),
          status: status || existing.status,
          currentVersion: Number(currentVersion) || existing.currentVersion,
        };

        try {
          inspection = await prisma.inspection.update({
            where: { id },
            data: updateData,
          });
        } catch {
          inspection = await sbUpdateInspection(id, updateData);
        }

        try {
          await prisma.inspectionAuditLog.create({
            data: {
              inspectionId: id,
              versionNumber: inspection.currentVersion,
              action: 'DRAFT_UPDATED',
              performedByName: inspectorName || 'QA Auditor',
              details: `Updated draft details for PO: ${poNumber || 'N/A'}`,
            },
          });
        } catch {
          // ignore audit log failure in fallback
        }
      } else {
        // ID provided but not found: validate uniqueness before creating
        const isAutoGenerated = !providedInspectionNumber || providedInspectionNumber.trim() === '';
        let targetNumber = (providedInspectionNumber && providedInspectionNumber.trim()) || '';
        if (targetNumber) {
          let conflict: any = null;
          try {
            conflict = await prisma.inspection.findUnique({
              where: { inspectionNumber: targetNumber },
            });
          } catch {
            conflict = await sbFindInspectionByNumber(targetNumber);
          }

          if (conflict) {
            return NextResponse.json(
              { error: `Report Number "${targetNumber}" is already in use by another inspection report.` },
              { status: 409 }
            );
          }
        } else {
          targetNumber = await generateInspectionNumber();
        }

        console.log(`[BACKEND ACTION] Creating new inspection draft with permanent report number: ${targetNumber} and client ID: ${id}`);
        const newRecordData = {
          id,
          inspectionNumber: targetNumber,
          poNumber: poNumber ?? '',
          poQuantity: Number(poQuantity) || 0,
          inspectionQuantity: Number(inspectionQuantity) || 0,
          factoryName: factoryName ?? '',
          agentName: agentName ?? '',
          season: season ?? '',
          buyerBrand: buyerBrand ?? '',
          styleNumber: styleNumber ?? '',
          productDescription: productDescription ?? '',
          inspectionDate: inspectionDate || new Date().toISOString().split('T')[0],
          inspectorName: inspectorName ?? '',
          visualAuditResult: visualAuditResult ?? 'PASS',
          packingAuditResult: packingAuditResult ?? 'PASS',
          overallResult: overallResult ?? 'PASS',
          comments: comments ?? '',
          itemsToCheck: typeof itemsToCheck === 'string' ? itemsToCheck : JSON.stringify(itemsToCheck),
          shipmentDetails: typeof shipmentDetails === 'string' ? shipmentDetails : JSON.stringify(shipmentDetails),
          cartonDetails: typeof cartonDetails === 'string' ? cartonDetails : JSON.stringify(cartonDetails),
          capDetails: typeof capDetails === 'string' ? capDetails : JSON.stringify(capDetails),
          status: status || 'draft',
          currentVersion: 1,
        };

        inspection = await safeInsertNewRecord(newRecordData, isAutoGenerated);

        try {
          await prisma.inspectionAuditLog.create({
            data: {
              inspectionId: inspection.id,
              versionNumber: 1,
              action: 'CREATED',
              performedByName: inspectorName || 'QA Auditor',
              details: `Created new inspection record ${inspection.inspectionNumber}`,
            },
          });
        } catch {
          // ignore audit log failure
        }
      }
    } else {
      // First-time creation without ID: validate uniqueness before creating
      const isAutoGenerated = !providedInspectionNumber || providedInspectionNumber.trim() === '';
      let targetNumber = (providedInspectionNumber && providedInspectionNumber.trim()) || '';
      if (targetNumber) {
        let conflict: any = null;
        try {
          conflict = await prisma.inspection.findUnique({
            where: { inspectionNumber: targetNumber },
          });
        } catch {
          conflict = await sbFindInspectionByNumber(targetNumber);
        }

        if (conflict) {
          return NextResponse.json(
            { error: `Report Number "${targetNumber}" is already in use by another inspection report.` },
            { status: 409 }
          );
        }
      } else {
        targetNumber = await generateInspectionNumber();
      }

      console.log(`[BACKEND ACTION] Creating new inspection draft with permanent report number: ${targetNumber}`);
      const newRecordData = {
        id: sbGenerateId(),
        inspectionNumber: targetNumber,
        poNumber: poNumber ?? '',
        poQuantity: Number(poQuantity) || 0,
        inspectionQuantity: Number(inspectionQuantity) || 0,
        factoryName: factoryName ?? '',
        agentName: agentName ?? '',
        season: season ?? '',
        buyerBrand: buyerBrand ?? '',
        styleNumber: styleNumber ?? '',
        productDescription: productDescription ?? '',
        inspectionDate: inspectionDate || new Date().toISOString().split('T')[0],
        inspectorName: inspectorName ?? '',
        visualAuditResult: visualAuditResult ?? 'PASS',
        packingAuditResult: packingAuditResult ?? 'PASS',
        overallResult: overallResult ?? 'PASS',
        comments: comments ?? '',
        itemsToCheck: typeof itemsToCheck === 'string' ? itemsToCheck : JSON.stringify(itemsToCheck),
        shipmentDetails: typeof shipmentDetails === 'string' ? shipmentDetails : JSON.stringify(shipmentDetails),
        cartonDetails: typeof cartonDetails === 'string' ? cartonDetails : JSON.stringify(cartonDetails),
        capDetails: typeof capDetails === 'string' ? capDetails : JSON.stringify(capDetails),
        status: status || 'draft',
        currentVersion: 1,
      };

      inspection = await safeInsertNewRecord(newRecordData, isAutoGenerated);

      try {
        await prisma.inspectionAuditLog.create({
          data: {
            inspectionId: inspection.id,
            versionNumber: 1,
            action: 'CREATED',
            performedByName: inspectorName || 'QA Auditor',
            details: `Created new inspection record ${inspection.inspectionNumber}`,
          },
        });
      } catch {
        // ignore audit log failure
      }
    }

    const currentId = inspection.id;

    // Synchronize nested relationships safely
    try {
      await prisma.inspectionMeasurement.deleteMany({ where: { inspectionId: currentId } });
      if (measurements.length > 0) {
        await prisma.inspectionMeasurement.createMany({
          data: measurements.map((m: any) => ({
            inspectionId: currentId,
            measurementPoint: m.measurementPoint || '',
            specRequired: m.specRequired || '',
            tolerance: m.tolerance || '',
            actualValues: typeof m.actualValues === 'string' ? m.actualValues : JSON.stringify(m.actualValues || []),
            result: m.result || 'PASS',
          })),
        });
      }

      await prisma.inspectionDefect.deleteMany({ where: { inspectionId: currentId } });
      if (defects.length > 0) {
        await prisma.inspectionDefect.createMany({
          data: defects.map((d: any) => ({
            inspectionId: currentId,
            defectCode: d.defectCode || '',
            description: d.description || '',
            location: d.location || '',
            severity: d.severity || 'Major',
            quantity: Number(d.quantity) || 1,
            photoUrl: d.photoUrl || '',
          })),
        });
      }

      await prisma.inspectionPhoto.deleteMany({ where: { inspectionId: currentId } });
      if (photos.length > 0) {
        await prisma.inspectionPhoto.createMany({
          data: photos.map((p: any) => ({
            inspectionId: currentId,
            type: p.type || 'inspection',
            photoUrl: p.photoUrl || '',
            description: p.description || '',
          })),
        });
      }
    } catch {
      // relational tables sync fallback
    }

    let updatedRecord: any = null;
    try {
      updatedRecord = await prisma.inspection.findUnique({
        where: { id: currentId },
        include: {
          measurements: true,
          defects: true,
          photos: true,
          versions: { orderBy: { versionNumber: 'desc' } },
          auditLogs: { orderBy: { timestamp: 'desc' } },
        },
      });
    } catch {
      updatedRecord = await sbFindInspectionById(currentId);
    }

    return NextResponse.json({ success: true, inspection: updatedRecord || inspection });
  } catch (error: any) {
    console.error('[BACKEND ERROR] Error saving inspection:', error);
    return NextResponse.json({ error: error.message || 'Failed to save inspection' }, { status: 500 });
  }
}
